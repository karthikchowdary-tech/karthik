# Tuple in Python
a = tuple((1, 2, 3, 4, 5))
print(a)
b = tuple("karthik")
print(b)

tup = (1,2)
print(tup)

# Using String
tup = ('nani','gopi', 'karthik')
print(tup)

# Using List
li = [1, 2, 4, 5, 6]
print(tuple(li))

# Using Built-in Function
tup = tuple('coastal')
print(tup)

# Tuple with Mixed Datatypes
tup = (5, 'Congrates', 7.5, False, [1, 2, 3], {'key': 'value'})
print(tup)

#Concatenation of Tuples
tup1 = (0, 1, 2, 3)
tup2 = ('Tcs', 'Ilm', 'infosis')
tup3 = tup1 + tup2
print(tup3)